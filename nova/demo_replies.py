DEMO_MAILBOX = "devstar4418@gcplab.me"
FIXTURES = Path(__file__).resolve().parent.parent / "examples" / "colleague-demo" / "replies"
TYPOS = {
    "recycled": "recylced",
    "renewable": "renewble",
    "polymer": "polymre",
    "product": "prodcut",
    "demonstration": "demonstation",
    "electricity": "electrcity",
    "packaging": "packagng",
    "maintenance": "maintenence",
    "annually": "anually",
}


def enabled_for(settings, case):
    return (
        settings.demo_auto_reply
        and settings.mail_mode == "gmail"
        and settings.gmail_supplier.casefold() == DEMO_MAILBOX
        and case.recipient.casefold() == DEMO_MAILBOX
        and re.fullmatch(
            r"(?:DEMO20-(?:0[1-9]|1[0-9]|20)|DEMO-AUTO-(?:PARTIAL|EMPTY|INVALID))", case.supplier_id
        )
        is not None
        and case.nart == case.supplier_id + "-ARTICLE"
        and case.supplier_name.startswith("Demo ")
    )


def pdf_document(lines, *, scanned=False):
    from reportlab.pdfgen.canvas import Canvas

    stream = io.BytesIO()
    canvas = Canvas(stream, invariant=1)
    wrapped = [line for raw in lines for line in (textwrap.wrap(raw, 85) or [""])]
    for start in range(0, len(wrapped), 44):
        page = wrapped[start : start + 44]
        if scanned:
            from PIL import Image, ImageDraw, ImageFont
            from reportlab.lib.utils import ImageReader

            bitmap = Image.new("RGB", (1240, 1754), "white")
            draw = ImageDraw.Draw(bitmap)
            font = ImageFont.load_default(size=22)
            for i, line in enumerate(page):
                draw.text((70, 80 + i * 34), line, fill="black", font=font)
            canvas.drawImage(ImageReader(bitmap), 0, 0, width=595, height=842)
        else:
            canvas.setFont("Helvetica", 10)
            for i, line in enumerate(page):
                canvas.drawString(45, 790 - i * 16, line)
        canvas.showPage()
    canvas.save()
    return stream.getvalue()


AUTO_ANSWERS = [
    ("Material composition", "Freetext", "80% recycled aluminium"),
    ("Certificate valid until", "Date", "2028-12-31"),
    ("Electricity sourcing", "Freetext", "Renewable electricity confirmed"),
    ("Net product weight", "Freetext", "1.25 kg"),
    ("Reporting year", "Freetext", "2026"),
    ("Transport mode", "Freetext", "Rail freight"),
]


def automatic_scenario(supplier_id, requested_fields, followup):
    marker = "SIMULATED SUPPLIER REPLY — NOVA automatic follow-up demonstration.\n"
    lines = [f"{supplier_id}-F{i}={value}" for i, (_, _, value) in enumerate(AUTO_ANSWERS, 1)]
    if followup:
        lines = [line for line in lines if line.split("=", 1)[0] in requested_fields]
        return (
            marker + "\nHere is the additional information you requested:\n" + "\n".join(lines),
            [],
            "completed follow-up",
        )
    if supplier_id.endswith("EMPTY"):
        return marker + "\nThank you. We received your request and will look into it.", [], "no answers"
    if supplier_id.endswith("PARTIAL"):
        return (
            marker + "\nHere are the first four answers:\n" + "\n".join(lines[:4]),
            [],
            "four of six answers",
        )
    lines[1] = supplier_id + "-F2=2028-13-40"
    document = pdf_document(["FICTIONAL SUPPLIER ANSWERS - INCLUDES INVALID DATE", *lines])
    return (
        marker + "\nOur answers are attached; please use the supplied entries.",
        [("answers-invalid-date.pdf", document)],
        "invalid date in PDF",
    )


def response_content(supplier_id, requested_fields=None, followup=False):
    if supplier_id.startswith("DEMO-AUTO-"):
        return automatic_scenario(supplier_id, requested_fields or [], followup)
    number = int(supplier_id[-2:])
    original = (FIXTURES / f"{supplier_id}.txt").read_text()
    answers = [line for line in original.splitlines() if line.startswith(supplier_id + "-F")]
    if followup and requested_fields is not None:
        answers = [line for line in answers if line.split("=", 1)[0] in requested_fields]
    if not answers:
        raise ValueError("Demo response fixture is empty")
    # Alter answer spelling only; routing/field references and quantities remain intact.
    if number % 5 != 1:

        def misspell(line):
            key, value = line.split("=", 1)
            for good, typo in TYPOS.items():
                value = re.sub(r"\b" + good + r"\b", typo, value)
            return key + "=" + value

        answers = [misspell(line) for line in answers]
    marker = "SIMULATED SUPPLIER REPLY — generated by NOVA for the fictional DEMO20 scenario.\n"
    mode = (number - 1) % 5
    if mode == 0:
        return marker + "\nHello, here are our confirmed answers:\n" + "\n".join(answers), [], "plain text"
    if mode == 1:
        prose = [
            "For " + line.split("=", 1)[0] + ", we confirm: " + line.split("=", 1)[1] + "."
            for line in answers
        ]
        return (
            marker + "\nHelo team, sorry for the speling mistakes.\n\n" + "\n\n".join(prose),
            [],
            "free text with typos",
        )
    if mode == 2:
        return (
            marker + "\nPlease see the attatched text answers.",
            [("supplier-answers.txt", "\n".join(answers).encode())],
            "TXT attachment with typos",
        )
    if mode == 3:
        pdf = pdf_document(["FICTIONAL DEMO SUPPLIER EVIDENCE", *answers])
        return (
            marker + "\nPlease see our answers in the attached PDF.",
            [("supplier-evidence.pdf", pdf)],
            "PDF with typos",
        )
    if number == 20:
        pdf = pdf_document(["FICTIONAL DEMO - SCANNED EVIDENCE", *answers], scanned=True)
        return (
            marker + "\nOur scanned answer sheet is attached.",
            [("scanned-supplier-evidence.pdf", pdf)],
            "scanned PDF with typos",
        )
    split = max(1, len(answers) // 2)
    pdf = pdf_document(["FICTIONAL DEMO SUPPLIER EVIDENCE", *answers[split:]])
    return (
        marker + "\nThese answers are in the email; the rest are in the PDF:\n" + "\n".join(answers[:split]),
        [("additional-evidence.pdf", pdf)],
        "email plus PDF with typos",
    )


def simulate_reply_job(factory, settings, job_id, token, target_id):
    from nova.worker import own_job

    with factory.begin() as db:
        job = own_job(db, job_id, token)
        draft = db.get(Draft, target_id)
        case = locked(db, Case, draft.case_id)
        if not enabled_for(settings, case) or draft.status != "sent":
            job.status = "cancelled"
            return
        external_id = "demo-simulated:" + draft.id
        if db.scalar(select(Message.id).where(Message.external_id == external_id)):
            job.status = "done"
            return
        # If a real supplier already replied, do not insert an additional scripted answer.
        if db.scalar(
            select(Message.id).where(Message.case_id == case.id, Message.created_at >= draft.created_at)
        ):
            job.status = "cancelled"
            return
        body, attachments, scenario = response_content(
            case.supplier_id, requested_fields=draft.requested_fields, followup=draft.kind == "auto_followup"
        )
        reply = ingest_message(
            db, settings, case.id, external_id, case.recipient, body, attachments, "demo-simulator"
        )
        audit(db, "demo-simulator", "reply.simulated", reply["id"], scenario=scenario, draft_id=draft.id)
        job.status = "done"
